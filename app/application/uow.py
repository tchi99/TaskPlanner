from __future__ import annotations

from datetime import date
from types import TracebackType
from typing import Protocol, Sequence
from uuid import UUID

from app.application.history import HistoryEvent
from app.domain import Project, Task, TaskAggregate, WorkType
from app.domain.capacity import AvailabilityBlock
from app.domain.time_blocks import ConfirmedTimeBlock
from app.domain.daily import DailyReview
from app.domain.weekly import WeeklyDecision, WeeklySubject
from app.domain.start import ResumePoint
from app.domain.work_sessions import WorkSession
from app.domain.availability_exceptions import AvailabilityException
from app.domain.recurring_availability import RecurringAvailabilityRule, RuleRevision
from datetime import datetime


class TaskRepository(Protocol):
    def add(self, task: Task) -> Task: ...
    def add_aggregate(self, aggregate: TaskAggregate) -> TaskAggregate: ...
    def get(self, task_id: UUID) -> Task | None: ...
    def get_aggregate(self, task_id: UUID) -> TaskAggregate | None: ...
    def list_inbox(self) -> Sequence[Task]: ...
    def list_all(self) -> Sequence[Task]: ...
    def list_by_project(self, project_id: UUID | None) -> Sequence[Task]: ...
    def save(self, task: Task) -> Task: ...
    def save_aggregate(self, aggregate: TaskAggregate) -> TaskAggregate: ...


class HistoryRepository(Protocol):
    def append(self, event: HistoryEvent) -> None: ...
    def append_many(self, events: Sequence[HistoryEvent]) -> None: ...


class HistoryReadRepository(Protocol):
    def get(self, event_id: UUID) -> HistoryEvent | None: ...
    """Read-only event projection; separate from the append-only event sink."""
    def list_all(self, before: datetime | None = None) -> Sequence[HistoryEvent]: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> Project: ...
    def get(self, project_id: UUID) -> Project | None: ...
    def list_all(self) -> Sequence[Project]: ...


class WorkTypeRepository(Protocol):
    def add(self, work_type: WorkType) -> WorkType: ...
    def get(self, work_type_id: UUID) -> WorkType | None: ...
    def list_all(self) -> Sequence[WorkType]: ...


class AvailabilityRepository(Protocol):
    def add(self, block: AvailabilityBlock) -> AvailabilityBlock: ...
    def get(self, block_id: UUID) -> AvailabilityBlock | None: ...
    def list_week(self, week_start: date) -> Sequence[AvailabilityBlock]: ...
    def delete(self, block_id: UUID) -> None: ...


class RecurringAvailabilityRepository(Protocol):
    def get(self, rule_id: UUID, owner_id: str) -> RecurringAvailabilityRule | None: ...
    def list_owner(self, owner_id: str) -> Sequence[RecurringAvailabilityRule]: ...
    def add(self, value: RecurringAvailabilityRule) -> None: ...
    def append_revision(self, value: RuleRevision, *, expected_version: int) -> None: ...


class AvailabilityExceptionRepository(Protocol):
    def get(self, exception_id: UUID, owner_id: str) -> AvailabilityException | None: ...
    def list_owner(self, owner_id: str) -> Sequence[AvailabilityException]: ...
    def add(self, value: AvailabilityException) -> None: ...
    def save(self, value: AvailabilityException, *, expected_version: int) -> None: ...


class WeeklyScheduleCommandRepository(Protocol):
    def get(self, owner_id: str, command_id: UUID): ...
    def add(self, owner_id: str, command_id: UUID, payload_hash: str, result: dict) -> None: ...


class ConfirmedTimeBlockRepository(Protocol):
    def get(self, booking_id: UUID) -> ConfirmedTimeBlock | None: ...
    def revise(self, booking: ConfirmedTimeBlock, *, status: str) -> None: ...
    def list_week(self, week_start: date) -> Sequence[ConfirmedTimeBlock]: ...
    def list_all_confirmed(self) -> Sequence[ConfirmedTimeBlock]: ...
    def add(self, block: ConfirmedTimeBlock) -> None: ...


class DailyReviewRepository(Protocol):
    def get(self, day: date, timezone_name: str) -> DailyReview | None: ...
    def list_before(self, day: date, timezone_name: str) -> Sequence[DailyReview]: ...
    def save(self, review: DailyReview) -> None: ...


class WeeklyReviewRepository(Protocol):
    def latest_task_interactions(self, before: datetime) -> dict[UUID, datetime]: ...
    def get(self, week_start: date, timezone_name: str,
            subject_kind: WeeklySubject, subject_id: UUID) -> WeeklyDecision | None: ...
    def list_week(self, week_start: date, timezone_name: str) -> Sequence[WeeklyDecision]: ...
    def save(self, decision: WeeklyDecision) -> None: ...


class ResumePointRepository(Protocol):
    def get(self, task_id: UUID) -> ResumePoint | None: ...
    def save(self, value: ResumePoint) -> None: ...


class WorkSessionRepository(Protocol):
    def add(self, value: WorkSession) -> None: ...
    def get(self, session_id: UUID) -> WorkSession | None: ...
    def get_active(self) -> WorkSession | None: ...
    def list_task(self, task_id: UUID) -> Sequence[WorkSession]: ...
    def list_all(self) -> Sequence[WorkSession]: ...
    def save(self, value: WorkSession, expected_revision: int) -> None: ...


class UnitOfWork(Protocol):
    availability: AvailabilityRepository
    recurring_availability: RecurringAvailabilityRepository
    availability_exceptions: AvailabilityExceptionRepository
    weekly_commands: WeeklyScheduleCommandRepository
    time_blocks: ConfirmedTimeBlockRepository
    daily_reviews: DailyReviewRepository
    weekly_reviews: WeeklyReviewRepository
    tasks: TaskRepository
    resume_points: ResumePointRepository
    work_sessions: WorkSessionRepository
    history: HistoryRepository
    history_read: HistoryReadRepository
    projects: ProjectRepository
    work_types: WorkTypeRepository
    schedule_scopes: object  # SQL adapter enforces owner, version and dated affiliation

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    def lock_planning(self) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
