from __future__ import annotations

from datetime import date
from types import TracebackType
from typing import Protocol, Sequence
from uuid import UUID

from app.application.history import HistoryEvent
from app.domain import Project, Task, TaskAggregate, WorkType
from app.domain.capacity import AvailabilityBlock
from app.domain.time_blocks import ConfirmedTimeBlock
from app.domain.daily import DailyReview


class TaskRepository(Protocol):
    def add(self, task: Task) -> Task: ...
    def add_aggregate(self, aggregate: TaskAggregate) -> TaskAggregate: ...
    def get(self, task_id: UUID) -> Task | None: ...
    def get_aggregate(self, task_id: UUID) -> TaskAggregate | None: ...
    def list_inbox(self) -> Sequence[Task]: ...
    def list_all(self) -> Sequence[Task]: ...
    def list_by_project(self, project_id: UUID | None) -> Sequence[Task]: ...
    def save(self, task: Task) -> Task: ...
    def save_aggregate(self, aggregate: TaskAggregate) -> TaskAggregate: ...


class HistoryRepository(Protocol):
    def append(self, event: HistoryEvent) -> None: ...
    def append_many(self, events: Sequence[HistoryEvent]) -> None: ...


class ProjectRepository(Protocol):
    def add(self, project: Project) -> Project: ...
    def get(self, project_id: UUID) -> Project | None: ...
    def list_all(self) -> Sequence[Project]: ...


class WorkTypeRepository(Protocol):
    def add(self, work_type: WorkType) -> WorkType: ...
    def get(self, work_type_id: UUID) -> WorkType | None: ...
    def list_all(self) -> Sequence[WorkType]: ...


class AvailabilityRepository(Protocol):
    def add(self, block: AvailabilityBlock) -> AvailabilityBlock: ...
    def get(self, block_id: UUID) -> AvailabilityBlock | None: ...
    def list_week(self, week_start: date) -> Sequence[AvailabilityBlock]: ...
    def delete(self, block_id: UUID) -> None: ...


class ConfirmedTimeBlockRepository(Protocol):
    def list_week(self, week_start: date) -> Sequence[ConfirmedTimeBlock]: ...
    def add(self, block: ConfirmedTimeBlock) -> None: ...


class DailyReviewRepository(Protocol):
    def get(self, day: date, timezone_name: str) -> DailyReview | None: ...
    def list_before(self, day: date, timezone_name: str) -> Sequence[DailyReview]: ...
    def save(self, review: DailyReview) -> None: ...


class UnitOfWork(Protocol):
    availability: AvailabilityRepository
    time_blocks: ConfirmedTimeBlockRepository
    daily_reviews: DailyReviewRepository
    tasks: TaskRepository
    history: HistoryRepository
    projects: ProjectRepository
    work_types: WorkTypeRepository

    def __enter__(self) -> UnitOfWork: ...
    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
